#!/usr/bin/env python3
"""
Automated LCOV Code Coverage Summary Generator for Flutter & Angular AI Agent & CI Pipelines.

Parses standard LCOV (lcov.info) coverage files generated by:
  - Flutter: `flutter test --coverage` -> coverage/lcov.info
  - Angular (Jest / Karma): `npm test -- --coverage` -> coverage/lcov.info

Generates a consolidated Markdown summary with status badges (🟢, 🟡, 🔴),
group breakdown by feature/directory, and top missed files. Writes to
$GITHUB_STEP_SUMMARY and an optional output file for PR comments.

Usage:
    python3 generate-lcov-summary.py [lcov_path] [output_path] [--title "Coverage Summary"]
    python3 generate-lcov-summary.py --lcov coverage/lcov.info --output target/coverage-summary.md
"""

import argparse
import glob
import os
import sys
from typing import Dict, List, Optional, Tuple


def pct(covered: int, missed: int) -> float:
    total = covered + missed
    return (covered / total * 100.0) if total > 0 else 100.0


def status_badge(percentage: float) -> str:
    if percentage >= 80.0:
        return "🟢"
    elif percentage >= 60.0:
        return "🟡"
    else:
        return "🔴"


def find_lcov_file(preferred_path: Optional[str] = None) -> Optional[str]:
    if preferred_path and os.path.exists(preferred_path):
        return preferred_path

    candidates = [
        "coverage/lcov.info",
        "coverage/coverage.info",
    ]
    for c in candidates:
        if os.path.exists(c):
            return c

    glob_candidates = glob.glob("**/coverage/**/lcov.info", recursive=True)
    if glob_candidates:
        return glob_candidates[0]

    return None


def extract_group_name(file_path: str) -> str:
    """Group file into a logical module or feature area."""
    normalized = file_path.replace("\\", "/").lstrip("./")

    # Flutter feature pattern: lib/features/{feature}
    if "lib/features/" in normalized:
        parts = normalized.split("lib/features/")[1].split("/")
        return f"feature:{parts[0]}"
    if "lib/core/" in normalized:
        return "core"
    if normalized.startswith("lib/"):
        parts = normalized.split("/")
        return parts[1] if len(parts) > 2 else "lib"

    # Angular feature pattern: src/app/features/{feature} or src/app/{feature}
    if "src/app/features/" in normalized:
        parts = normalized.split("src/app/features/")[1].split("/")
        return f"feature:{parts[0]}"
    if "src/app/core/" in normalized:
        return "core"
    if "src/app/" in normalized:
        parts = normalized.split("src/app/")[1].split("/")
        return parts[0] if len(parts) > 1 else "app"

    # Fallback to parent directory
    parts = normalized.split("/")
    if len(parts) > 1:
        return "/".join(parts[:2])
    return "root"


def parse_lcov(lcov_path: str) -> Tuple[Dict[str, Dict[str, int]], Dict[str, int], List[Tuple[int, int, float, str, str]]]:
    groups: Dict[str, Dict[str, int]] = {}
    total = {
        "line_h": 0, "line_f": 0,
        "func_h": 0, "func_f": 0,
        "br_h": 0, "br_f": 0,
        "files": 0,
    }
    file_missed: List[Tuple[int, int, float, str, str]] = []

    current_file: Optional[str] = None
    cur_lf = 0
    cur_lh = 0
    cur_fnf = 0
    cur_fnh = 0
    cur_brf = 0
    cur_brh = 0

    with open(lcov_path, mode="r", encoding="utf-8", errors="replace") as f:
        for raw_line in f:
            line = raw_line.strip()
            if line.startswith("SF:"):
                current_file = line[3:].strip()
                cur_lf = cur_lh = cur_fnf = cur_fnh = cur_brf = cur_brh = 0
            elif line.startswith("LF:"):
                cur_lf = int(line[3:].strip() or 0)
            elif line.startswith("LH:"):
                cur_lh = int(line[3:].strip() or 0)
            elif line.startswith("FNF:"):
                cur_fnf = int(line[4:].strip() or 0)
            elif line.startswith("FNH:"):
                cur_fnh = int(line[4:].strip() or 0)
            elif line.startswith("BRF:"):
                cur_brf = int(line[4:].strip() or 0)
            elif line.startswith("BRH:"):
                cur_brh = int(line[4:].strip() or 0)
            elif line == "end_of_record":
                if current_file:
                    group = extract_group_name(current_file)
                    if group not in groups:
                        groups[group] = {
                            "line_h": 0, "line_f": 0,
                            "func_h": 0, "func_f": 0,
                            "br_h": 0, "br_f": 0,
                            "files": 0,
                        }
                    groups[group]["line_h"] += cur_lh
                    groups[group]["line_f"] += cur_lf
                    groups[group]["func_h"] += cur_fnh
                    groups[group]["func_f"] += cur_fnf
                    groups[group]["br_h"] += cur_brh
                    groups[group]["br_f"] += cur_brf
                    groups[group]["files"] += 1

                    total["line_h"] += cur_lh
                    total["line_f"] += cur_lf
                    total["func_h"] += cur_fnh
                    total["func_f"] += cur_fnf
                    total["br_h"] += cur_brh
                    total["br_f"] += cur_brf
                    total["files"] += 1

                    missed_lines = cur_lf - cur_lh
                    if missed_lines > 0:
                        file_pct = pct(cur_lh, missed_lines)
                        file_missed.append((missed_lines, cur_lh, file_pct, group, current_file))

                current_file = None

    return groups, total, file_missed


def generate_summary(lcov_path: str, title: Optional[str] = None) -> str:
    groups, total, file_missed = parse_lcov(lcov_path)

    tot_line_m = total["line_f"] - total["line_h"]
    tot_line_pct = pct(total["line_h"], tot_line_m)

    tot_br_m = total["br_f"] - total["br_h"]
    tot_br_pct = pct(total["br_h"], tot_br_m)

    tot_fn_m = total["func_f"] - total["func_h"]
    tot_fn_pct = pct(total["func_h"], tot_fn_m)

    header_title = title or "Unified LCOV Code Coverage Summary"

    lines = [
        f"## 📊 {header_title}",
        "",
        f"> **Overall Coverage**: {status_badge(tot_line_pct)} **{tot_line_pct:.1f}%** Lines ({total['line_h']}/{total['line_f']}) | "
        f"{status_badge(tot_fn_pct)} **{tot_fn_pct:.1f}%** Functions ({total['func_h']}/{total['func_f']}) | "
        f"{status_badge(tot_br_pct)} **{tot_br_pct:.1f}%** Branches ({total['br_h']}/{total['br_f']})",
        "",
        "### 📦 Feature / Module Breakdown",
        "",
        "| Module / Scope | Line Coverage | Function Coverage | Branch Coverage | Files | Status |",
        "| :--- | :--- | :--- | :--- | :---: | :---: |",
    ]

    for grp, data in sorted(groups.items()):
        l_miss = data["line_f"] - data["line_h"]
        l_pct = pct(data["line_h"], l_miss)

        f_miss = data["func_f"] - data["func_h"]
        f_pct = pct(data["func_h"], f_miss)

        b_miss = data["br_f"] - data["br_h"]
        b_pct = pct(data["br_h"], b_miss)

        badge = status_badge(l_pct)
        status_text = "Pass" if l_pct >= 80.0 else ("Warning" if l_pct >= 60.0 else "Fail")

        lines.append(
            f"| `{grp}` | {badge} {l_pct:.1f}% ({data['line_h']}/{data['line_f']}) | "
            f"{f_pct:.1f}% ({data['func_h']}/{data['func_f']}) | "
            f"{b_pct:.1f}% ({data['br_h']}/{data['br_f']}) | "
            f"{data['files']} | {badge} {status_text} |"
        )

    lines.append(
        f"| **Total** | {status_badge(tot_line_pct)} **{tot_line_pct:.1f}%** ({total['line_h']}/{total['line_f']}) | "
        f"**{tot_fn_pct:.1f}%** ({total['func_h']}/{total['func_f']}) | "
        f"**{tot_br_pct:.1f}%** ({total['br_h']}/{total['br_f']}) | "
        f"**{total['files']}** | {status_badge(tot_line_pct)} **{'Pass' if tot_line_pct >= 80.0 else 'Review'}** |"
    )

    if file_missed:
        file_missed.sort(key=lambda x: x[0], reverse=True)
        top_missed = file_missed[:10]
        lines.extend([
            "",
            "<details>",
            f"<summary>🔍 <b>Top {len(top_missed)} Files with Missed Lines (click to expand)</b></summary>",
            "",
            "| Scope | File | Coverage | Missed Lines |",
            "| :--- | :--- | :--- | :---: |",
        ])
        for missed, hit, c_pct, grp, fpath in top_missed:
            lines.append(f"| `{grp}` | `{fpath}` | {c_pct:.1f}% ({hit}/{hit + missed}) | {missed} |")
        lines.append("</details>")

    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate Markdown Summary from LCOV info")
    parser.add_argument("lcov_pos", nargs="?", default=None, help="LCOV info file path (positional)")
    parser.add_argument("out_pos", nargs="?", default=None, help="Output markdown file path (positional)")
    parser.add_argument("--lcov", dest="lcov_flag", default=None, help="LCOV info file path")
    parser.add_argument("--output", "-o", dest="out_flag", default=None, help="Output markdown file path")
    parser.add_argument("--title", dest="title", default=None, help="Custom markdown report title")

    args = parser.parse_args()

    preferred_lcov = args.lcov_flag or args.lcov_pos
    output_path = args.out_flag or args.out_pos
    lcov_file = find_lcov_file(preferred_lcov)

    if not lcov_file:
        content = "## 📊 LCOV Code Coverage Summary\n\n> [!WARNING]\n> No LCOV coverage report (lcov.info) found.\n"
    else:
        content = generate_summary(lcov_file, args.title)

    # Print to stdout
    print(content)

    # Append to GitHub Step Summary if available
    summary_path = os.getenv("GITHUB_STEP_SUMMARY")
    if summary_path:
        try:
            with open(summary_path, mode="a", encoding="utf-8") as f:
                f.write(content)
        except Exception as e:
            sys.stderr.write(f"Warning: Could not write to GITHUB_STEP_SUMMARY: {e}\n")

    # Write to target output file if specified
    if output_path:
        out_dir = os.path.dirname(os.path.abspath(output_path))
        os.makedirs(out_dir, exist_ok=True)
        with open(output_path, mode="w", encoding="utf-8") as f:
            f.write(content)


if __name__ == "__main__":
    main()
